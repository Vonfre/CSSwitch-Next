import { build } from 'esbuild';
import { mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const repo = new URL('../../', import.meta.url);
const out = new URL('scripts/openscience-mcp/', repo);
mkdirSync(out, { recursive: true });
await build({ entryPoints: [fileURLToPath(new URL('mcp/openscience/server.ts', repo))],
  outfile: fileURLToPath(new URL('server.mjs', out)), bundle: true, platform: 'node', format: 'esm', target: 'node22',
  nodePaths: [fileURLToPath(new URL('node_modules/', new URL('../', import.meta.url)))],
  banner: { js: '// OpenScience adapters: Apache-2.0, Copyright 2026 InkVell Inc. (Synthetic Sciences).\n// See LICENSE and NOTICE in this directory. Generated by npm run build:mcp.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);' } });
for (const name of ['LICENSE', 'NOTICE']) copyFileSync(new URL(`mcp/openscience/${name}`, repo), new URL(name, out));
for (const name of ['undici', 'zod']) copyFileSync(new URL(`../node_modules/${name}/LICENSE`, import.meta.url), new URL(`${name}-LICENSE`, out));
